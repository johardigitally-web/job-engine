#!/usr/bin/env node
/**
 * build-worklist.mjs - turn verified roles into a ranked, ready-to-submit list.
 *
 * Why this exists. Across a real three week campaign the numbers were stark:
 * 28 applications sent by email produced 0 responses, while the single
 * application put through a company's own form produced a booked interview.
 * Most ATS forms sit behind reCAPTCHA or Turnstile and cannot be submitted by a
 * script, and they should not be. So the engine does everything up to the submit
 * button and you spend two minutes clicking it.
 *
 * Reads state/roles.json (written by the scan and stamped by check-live.mjs)
 * and you.json, and writes out/APPLY-NOW.md.
 *
 *   node src/build-worklist.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = (...p) => path.join(ROOT, ...p);

const readJson = (p, fallback) => {
  try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch { return fallback; }
};

const you = readJson(P('you.json'), null);
if (!you) {
  console.error('No you.json found. Copy you.example.json to you.json and fill it in.');
  process.exit(1);
}
const roles = readJson(P('state', 'roles.json'), []);
const applied = readJson(P('state', 'applied.json'), { submitted: [] });
const doneUrls = new Set((applied.submitted || []).map((a) => String(a.url)));

const clean = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();
const trunc = (s, n) => { const t = clean(s); return t.length > n ? t.slice(0, n).replace(/[ ,;.]+$/, '') + '...' : t; };

const HOME = String(you.location.country || '').trim();
const homeRe = HOME ? new RegExp('\\b' + HOME.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\b', 'i') : null;
const isHome = (r) => homeRe && homeRe.test(clean(r.locationPolicy));
const isAnywhere = (r) => /worldwide|anywhere|everywhere|global|remote only/i.test(clean(r.locationPolicy));

// Drop anything check-live.mjs found dead. Postings decay roughly a quarter in
// eleven days, and a list that still shows them wastes the only scarce resource
// here, which is your time at the keyboard.
const rows = roles
  .filter((r) => !doneUrls.has(String(r.applyUrl || r.url)))
  .filter((r) => r.live !== 'dead' && r.live !== 'closed')
  .sort((a, b) => (b.score || 0) - (a.score || 0));

const dropped = roles.filter((r) => r.live === 'dead' || r.live === 'closed').length;

const tierA = rows.filter((r) => isHome(r));
const tierB = rows.filter((r) => !isHome(r) && isAnywhere(r));
const tierC = rows.filter((r) => !isHome(r) && !isAnywhere(r));

const L = [];
L.push('# Apply now');
L.push('');
L.push('Generated by `src/build-worklist.mjs`, ranked by fit. Work down from the top.');
L.push('');
L.push('**The form is the route.** Email a company only when the posting asks for email,');
L.push('or a named person invited it. Measured on a real campaign: 28 emails produced 0');
L.push('responses, and 21 of them went to info@, hello@ or support@ addresses, which are');
L.push('sales and support desks that never reach anyone hiring.');
L.push('');
L.push('---');
L.push('');
L.push('## Your standard answers');
L.push('');
L.push('| Field | Answer |');
L.push('|---|---|');
L.push('| Name | ' + clean(you.name) + ' |');
L.push('| Email | ' + clean(you.email) + ' |');
if (you.phone) L.push('| Phone | ' + clean(you.phone) + ' |');
L.push('| Location | ' + clean(you.location.city) + ', ' + HOME + ' (' + clean(you.location.timezone) + ') |');
if (you.linkedin) L.push('| LinkedIn | ' + clean(you.linkedin) + ' |');
if (you.website) L.push('| Website | ' + clean(you.website) + ' |');
if (you.cvFile) L.push('| CV file | `' + clean(you.cvFile) + '` |');
if (you.cvUrl) L.push('| CV as a link | ' + clean(you.cvUrl) + ' |');
if (you.rate && you.rate.hourly) L.push('| Hourly rate | ' + clean(you.rate.hourly) + ' |');
if (you.rate && you.rate.monthly) L.push('| Monthly | ' + clean(you.rate.monthly) + ' |');
if (you.availability) L.push('| Availability | ' + clean(you.availability) + ' |');
L.push('');
if ((you.provenNumbers || []).length) {
  L.push('**Figures you can use anywhere:** ' + you.provenNumbers.map(clean).join(' · '));
  L.push('');
}
if ((you.neverSay || []).length) {
  L.push('**Never say:** ' + you.neverSay.map(clean).join(' · '));
  L.push('');
}

function section(title, list, note) {
  if (!list.length) return;
  L.push('---');
  L.push('');
  L.push('## ' + title + ' (' + list.length + ')');
  if (note) { L.push(''); L.push(note); }
  L.push('');
  let i = 0;
  for (const r of list) {
    i += 1;
    L.push('### ' + i + '. ' + clean(r.title) + '  ·  ' + clean(r.company) + '  [fit ' + (r.score || 0) + ']');
    L.push('');
    L.push('**Apply:** ' + (clean(r.applyUrl) || clean(r.url)));
    if (r.applyMethod) L.push('**Via:** ' + trunc(r.applyMethod, 200));
    if (r.locationPolicy) L.push('**Eligibility:** ' + trunc(r.locationPolicy, 300));
    if (r.pay) L.push('**Pay:** ' + trunc(r.pay, 260));
    if (r.live === 'unknown') L.push('**Note:** liveness could not be confirmed (' + clean(r.liveDetail) + '). Check it is still open first.');
    if (r.hook) { L.push(''); L.push('**Open with this** (found on their own site):'); L.push('> ' + trunc(r.hook, 700)); }
    const qs = (r.screeningQuestions || []).map(clean).filter((q) => q.length > 8);
    if (qs.length) {
      L.push('');
      L.push('**They ask:**');
      for (const q of qs.slice(0, 8)) L.push('- ' + trunc(q, 300));
    }
    L.push('');
  }
}

section('Tier A: open to ' + HOME + ', so eligibility is not a risk', tierA,
  'Start here. Postings that name your country are far less contested than worldwide ones.');
section('Tier B: worldwide or remote-anywhere', tierB,
  'Eligibility taken from the posting itself, not inferred.');
section('Tier C: remote, eligibility not stated', tierC,
  'Worth a look, but read the eligibility line before spending time.');

fs.mkdirSync(P('out'), { recursive: true });
fs.writeFileSync(P('out', 'APPLY-NOW.md'), L.join('\n'), 'utf8');
console.log('Tier A (' + HOME + '): ' + tierA.length);
console.log('Tier B (worldwide): ' + tierB.length);
console.log('Tier C (other):     ' + tierC.length);
console.log('dropped as dead or already submitted: ' + (dropped + doneUrls.size));
console.log('\nout/APPLY-NOW.md written');
